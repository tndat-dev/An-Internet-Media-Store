def newspaper(
    index: int,
    *,
    title: str,
    publisher: str,
    editor: str,
    frequency: str,
    issn: str,
    sections: str,
    description: str,
    original_value: int,
    current_price: int,
    stock: int,
    category: str = "News",
) -> dict:
    return {
        "product_type": "NEWSPAPER",
        "title": title,
        # Newspapers have no genre, so default the browsable category to "News" (overridable per item).
        "category": category,
        "general_description": description,
        "barcode": f"SEED-NEWS-{index:03d}",
        "image_url": demo_cover("Newspaper", title, "334155"),
        "original_value": money(original_value),
        "current_price": money(current_price),
        "weight": Decimal("0.20"),
        "stock_quantity": stock,
        "type_details": {
            "publisher": publisher,
            "publication_date": date(2026, 6, 1),
            "issue_number": f"2026-{index:03d}",
            "editor_in_chief": editor,
            "publication_frequency": frequency,
            "issn": issn,
            "language": "English",
            "sections": sections,
        },
    }


