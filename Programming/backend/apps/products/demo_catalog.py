from __future__ import annotations

from datetime import date
from decimal import Decimal
from urllib.parse import quote


def money(value: int) -> Decimal:
    return Decimal(str(value))


def book_cover(isbn: str) -> str:
    return f"https://covers.openlibrary.org/b/isbn/{isbn}-L.jpg"


def demo_cover(label: str, title: str, background: str) -> str:
    text = quote(f"{label}: {title}", safe="")
    return f"https://placehold.co/600x900/{background}/ffffff.png?text={text}"


def book(
    index: int,
    *,
    title: str,
    authors: str,
    publisher: str,
    publication_date: date,
    pages: int,
    genre: str,
    isbn: str,
    description: str,
    original_value: int,
    current_price: int,
    stock: int,
    category: str | None = None,
) -> dict:
    return {
        "product_type": "BOOK",
        "title": title,
        # Category is the browsable subject/genre, distinct from the medium (product_type).
        "category": category or genre,
        "general_description": description,
        "barcode": f"SEED-BOOK-{index:03d}",
        "image_url": book_cover(isbn),
        "original_value": money(original_value),
        "current_price": money(current_price),
        "weight": Decimal("0.55"),
        "stock_quantity": stock,
        "type_details": {
            "authors": authors,
            "cover_type": "Paperback",
            "publisher": publisher,
            "publication_date": publication_date,
            "pages": pages,
            "language": "English",
            "genre": genre,
        },
    }


